function buildProjectTitle(idea: string) {
  const normalized = idea.trim().replace(/\s+/g, " ");
  if (!normalized) return "Generated Agent App";
  if (normalized.length <= 72) return normalized;
  return `${normalized.slice(0, 69).trim()}...`;
}
