import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import type { AgentResult, GeneratedFilePayload, ProjectState } from "@/lib/project-types";

type FileJsonPayload = {
  files?: Array<{
    path?: unknown;
    content?: unknown;
    language?: unknown;
  }>;
};

export async function writeGeneratedFiles(projectId: string, files: GeneratedFilePayload[]) {
  const root = path.resolve(process.cwd(), "generated-projects", projectId);
  await mkdir(root, { recursive: true });

  const written: GeneratedFilePayload[] = [];

  for (const file of files) {
    const safePath = sanitizeRelativePath(file.path);
    const target = path.resolve(root, safePath);

    if (!target.startsWith(root + path.sep)) {
      throw new Error(`Unsafe generated file path: ${file.path}`);
    }

    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, file.content, "utf8");
    written.push({
      path: safePath,
      content: file.content,
      language: file.language || inferLanguage(safePath),
    });
  }

  return written;
}

export function extractGeneratedFiles(result: AgentResult, project: ProjectState) {
  if (result.generatedFiles?.length) return normalizeFiles(result.generatedFiles);

  const parsed = parseFilesFromOutput(result.output);
  if (parsed.length) return parsed;

  return buildFallbackProjectFiles(project, result.output);
}

export function formatGeneratedFileSummary(files: GeneratedFilePayload[]) {
  return [
    "## Generated Files",
    "",
    ...files.map((file) => `- \`${file.path}\` (${file.language || inferLanguage(file.path)})`),
  ].join("\n");
}

function parseFilesFromOutput(output: string) {
  const jsonBlock = output.match(/```json\s*([\s\S]*?)```/i);
  if (!jsonBlock?.[1]) return [];

  try {
    const payload = JSON.parse(jsonBlock[1]) as FileJsonPayload;
    return normalizeFiles(
      (payload.files || []).flatMap((file) => {
        if (typeof file.path !== "string" || typeof file.content !== "string") return [];
        return [
          {
            path: file.path,
            content: file.content,
            language: typeof file.language === "string" ? file.language : undefined,
          },
        ];
      })
    );
  } catch {
    return [];
  }
}

function normalizeFiles(files: GeneratedFilePayload[]) {
  const seen = new Set<string>();
  return files.flatMap((file) => {
    const safePath = sanitizeRelativePath(file.path);
    if (seen.has(safePath)) return [];
    seen.add(safePath);
    return [
      {
        path: safePath,
        content: file.content,
        language: file.language || inferLanguage(safePath),
      },
    ];
  });
}

function sanitizeRelativePath(filePath: string) {
  const normalized = filePath.replaceAll("\\", "/").replace(/^\/+/, "");
  const parts = normalized.split("/").filter(Boolean);

  if (!parts.length || parts.some((part) => part === "." || part === "..")) {
    throw new Error(`Unsafe generated file path: ${filePath}`);
  }

  return parts.join("/");
}

function inferLanguage(filePath: string) {
  const ext = path.extname(filePath).slice(1);
  if (ext === "tsx" || ext === "ts" || ext === "json" || ext === "css" || ext === "md") return ext;
  return "text";
}

